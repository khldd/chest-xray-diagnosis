"""Generate configs/bench/<arch>_<variant>[_s<seed>].yaml for the architecture study.

Every run uses the same recipe as the DenseNet121 ablations (5 epochs, Adam 1e-4, 224 px,
flip augmentation, same patient split); only the architecture and one choice change:
  bce       fine-tuned, plain BCE (the best recipe from the DenseNet121 ablation)
  weighted  fine-tuned, weighted BCE
  frozen    backbone frozen, only the new head trained, plain BCE
Each run also saves val/test predictions and Grad-CAM localisation scores.

Usage (repo root):  python scripts/make_bench_configs.py
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "configs" / "bench"
ARCHS = ["densenet121", "resnet50", "efficientnet_b0", "convnext_tiny"]
VARIANTS = {
    "bce": {"loss": "bce", "freeze": False},
    "weighted": {"loss": "weighted_bce", "freeze": False},
    "frozen": {"loss": "bce", "freeze": True},
}
EXTRA_SEEDS = {("densenet121", "bce"): [1, 2], ("densenet121", "weighted"): [1, 2]}

TEMPLATE = """# Generated by scripts/make_bench_configs.py: {arch}, {variant}, seed {seed}
data:
  num_workers: 4
  cache: true
model:
  name: {arch}
  freeze_backbone: {freeze}
train:
  epochs: 5
  loss: {loss}
  seed: {seed}
  amp: true
  predict: true
  localize: true
  output_dir: /kaggle/working/{run}
  mlflow_experiment: chest-xray-benchmark
"""


def run_names() -> list[tuple[str, str, str, int]]:
    runs = []
    for arch in ARCHS:
        for variant in VARIANTS:
            runs.append((f"{arch}_{variant}", arch, variant, 0))
            for seed in EXTRA_SEEDS.get((arch, variant), []):
                runs.append((f"{arch}_{variant}_s{seed}", arch, variant, seed))
    return runs


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for run, arch, variant, seed in run_names():
        v = VARIANTS[variant]
        text = TEMPLATE.format(arch=arch, variant=variant, seed=seed, run=run, loss=v["loss"],
                               freeze=str(v["freeze"]).lower())
        (OUT / f"{run}.yaml").write_text(text, encoding="utf-8")
    print(f"wrote {len(run_names())} configs to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
