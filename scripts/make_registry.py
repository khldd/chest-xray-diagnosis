"""Write models/registry.json (the models the API serves) from the benchmark outputs.

For each served architecture it takes the plain-BCE run (seed 0): val/test mean AUC and
parameter count from its metrics.json / predictions, the temperature fitted on validation by
scripts/analyze_models.py, and the ONNX CPU latency from results/latency_ms.json. The files
themselves (models/bench/<arch>.onnx/.pth) are produced by src.export_onnx and stay out of git.

Usage (repo root):
  PYTHONPATH=. python scripts/make_registry.py [--default convnext_tiny]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from src.models.factory import get_arch

ROOT = Path(__file__).resolve().parent.parent
ARCHS = ["convnext_tiny", "densenet121", "resnet50", "efficientnet_b0"]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bench", default=str(ROOT / "kaggle_outputs" / "bench"))
    ap.add_argument("--temperatures", default=str(ROOT / "results" / "temperatures.json"))
    ap.add_argument("--benchmark-csv", default=str(ROOT / "results" / "benchmark.csv"))
    ap.add_argument("--latency", default=str(ROOT / "results" / "latency_ms.json"))
    ap.add_argument("--out", default=str(ROOT / "models" / "registry.json"))
    ap.add_argument("--default", default="convnext_tiny")
    args = ap.parse_args()

    temps = json.loads(Path(args.temperatures).read_text(encoding="utf-8"))
    latency = json.loads(Path(args.latency).read_text(encoding="utf-8"))
    test_auc = {}
    for line in Path(args.benchmark_csv).read_text(encoding="utf-8").splitlines()[1:]:
        cells = line.split(",")
        test_auc[cells[0]] = float(cells[1])

    models = []
    for arch in ARCHS:
        run = f"{arch}_bce"
        metrics = json.loads(
            (Path(args.bench) / run / run / "metrics.json").read_text(encoding="utf-8")
        )
        models.append({
            "id": arch,
            "arch": arch,
            "display_name": get_arch(arch).display,
            "onnx": f"bench/{arch}.onnx",
            "pth": f"bench/{arch}.pth",
            "temperature": round(temps[run]["T"], 4),
            "val_mean_auc": round(metrics["best_val_auc"], 4),
            "test_mean_auc": round(test_auc[run], 4),
            "n_parameters": metrics.get("n_parameters"),
            "latency_ms_cpu": latency.get(arch),
            "default": arch == args.default,
            "in_ensemble": True,
        })
    out = {"note": "Generated by scripts/make_registry.py; paths relative to this file.",
           "models": models}
    Path(args.out).write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: " + ", ".join(m["id"] for m in models))


if __name__ == "__main__":
    main()
